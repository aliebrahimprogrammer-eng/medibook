
package com.ga.userservice.cucumber;

import io.cucumber.java.en.Given;
import io.cucumber.java.en.When;
import io.cucumber.java.en.Then;
import io.restassured.response.Response;
import lombok.RequiredArgsConstructor;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

import java.util.Map;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

@RequiredArgsConstructor
public class UserLoginSteps {

    private final ScenarioState state;
    private final JdbcTemplate jdbcTemplate;

    @Given("I have a registered and email-verified user")
    public void iHaveARegisteredAndEmailVerifiedUser() {

        state.setEmail(
                "cucumber-login-" + UUID.randomUUID() + "@example.com"
        );

        state.setPassword("SecurePass123!");
        state.setFirstName("Cucumber");
        state.setLastName("LoginTester");

        // Register a new user through the actual API.
        Response registrationResponse = state.request()
                .body("""
                        {
                            "email": "%s",
                            "password": "%s",
                            "firstName": "%s",
                            "lastName": "%s",
                            "phone": "+97330000000"
                        }
                        """.formatted(
                        state.getEmail(),
                        state.getPassword(),
                        state.getFirstName(),
                        state.getLastName()
                ))
                .when()
                .post("/api/auth/register");

        assertEquals(
                201,
                registrationResponse.getStatusCode(),
                "User registration should succeed before login"
        );

        // Retrieve the verification token generated by the application.
        String verificationToken = jdbcTemplate.queryForObject(
                """
                SELECT evt.token
                FROM email_verification_tokens evt
                JOIN users u ON u.id = evt.user_id
                WHERE u.email = ?
                ORDER BY evt.created_at DESC
                LIMIT 1
                """,
                String.class,
                state.getEmail()
        );

        assertNotNull(
                verificationToken,
                "A verification token should have been generated"
        );

        // Verify the email using the actual API.
        Response verificationResponse = state.request()
                .queryParam("token", verificationToken)
                .when()
                .get("/api/auth/verify-email");

        assertEquals(
                204,
                verificationResponse.getStatusCode(),
                "Email verification should succeed"
        );
    }

    @When("I submit the login request with valid credentials")
    public void iSubmitTheLoginRequestWithValidCredentials() {

        state.setResponse(
                state.request()
                        .body("""
                                {
                                    "email": "%s",
                                    "password": "%s"
                                }
                                """.formatted(
                                state.getEmail(),
                                state.getPassword()
                        ))
                        .when()
                        .post("/api/auth/login")
        );
    }

    @Then("the login should be successful")
    public void theLoginShouldBeSuccessful() {

        assertEquals(
                200,
                state.getResponse().getStatusCode(),
                "Login should return HTTP 200 OK"
        );
    }

    @Then("the response should contain a JWT token")
    public void theResponseShouldContainAJwtToken() {

        String token = state.getResponse()
                .jsonPath()
                .getString("token");

        assertNotNull(token, "JWT token should not be null");
        assertFalse(token.isBlank(), "JWT token should not be empty");
    }

    @Given("I have a registered user")
    public void iHaveARegisteredUser() {

        state.setEmail("cucumber-invalid-" + UUID.randomUUID() + "@example.com");
        state.setPassword("SecurePass123!");
        state.setFirstName("Cucumber");
        state.setLastName("InvalidLoginTester");

        Response registrationResponse = state.request()
                .body("""
                {
                    "email": "%s",
                    "password": "%s",
                    "firstName": "%s",
                    "lastName": "%s",
                    "phone": "+97330000000"
                }
                """.formatted(
                        state.getEmail(),
                        state.getPassword(),
                        state.getFirstName(),
                        state.getLastName()
                ))
                .when()
                .post("/api/auth/register");

        assertEquals(201, registrationResponse.getStatusCode());

        String verificationToken = jdbcTemplate.queryForObject(
                """
                SELECT evt.token
                FROM email_verification_tokens evt
                JOIN users u ON u.id = evt.user_id
                WHERE u.email = ?
                ORDER BY evt.created_at DESC
                LIMIT 1
                """,
                String.class,
                state.getEmail()
        );

        Response verificationResponse = state.request()
                .when()
                .get("/api/auth/verify-email?token=" + verificationToken);

        assertEquals(204, verificationResponse.getStatusCode());

        Map<String, Object> userState = jdbcTemplate.queryForMap(
                "SELECT status, email_verified FROM users WHERE email = ?",
                state.getEmail()
        );

        System.out.println("User state before invalid login: " + userState);
    }

    @When("I submit the login request with an incorrect password")
    public void iSubmitLoginWithIncorrectPassword() {

        state.setResponse(
                state.request()
                        .body("""
                            {
                                "email": "%s",
                                "password": "WrongPassword123!"
                            }
                            """.formatted(state.getEmail()))
                        .when()
                        .post("/api/auth/login")
        );

    }

    @Then("the login should be rejected")
    public void theLoginShouldBeRejected() {

        assertEquals(
                401,
                state.getResponse().getStatusCode(),
                "Invalid credentials should return HTTP 401 Unauthorized"
        );
    }
}
